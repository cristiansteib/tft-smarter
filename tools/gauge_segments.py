#!/usr/bin/env python3
"""Generates SEG_SPANS / SEG_IDX for src/main.cpp: the scanline spans of every gauge segment.

The firmware used to compute each segment at run time (4x sin/cos in float, then two Adafruit_GFX
fillTriangle calls, which divide on every scanline): ~2.5 ms per segment on the Mega. This script does the
same maths offline - float32 like the AVR, truncating casts, and a line-by-line copy of
Adafruit_GFX::fillTriangle - so the table reproduces the old output pixel for pixel.
Run it again if the ring radii or the segment geometry change:  python3 tools/gauge_segments.py
"""
import math
import struct

f32 = lambda x: struct.unpack('f', struct.pack('f', x))[0]
D2R = f32(0.017453292519943295)
SEGS = 30
RINGS = [(62, 55), (53, 47), (45, 39)]   # (outer, inner) radius of the load gauges, the inner rings, the GPU power ring


def corner(cx, cy, r, a):
    # int x = g.cx + g.ro * cos(a): float32 maths, truncated; centres are >= 88 so everything is positive
    return int(f32(cx + f32(r * f32(math.cos(a))))) - cx, int(f32(cy + f32(r * f32(math.sin(a))))) - cy


def triangle(x0, y0, x1, y1, x2, y2):
    """Adafruit_GFX::fillTriangle, returning (y, a, b) hlines."""
    if y0 > y1: y0, y1, x0, x1 = y1, y0, x1, x0
    if y1 > y2: y2, y1, x2, x1 = y1, y2, x1, x2
    if y0 > y1: y0, y1, x0, x1 = y1, y0, x1, x0
    out = []
    if y0 == y2:
        return [(y0, min(x0, x1, x2), max(x0, x1, x2))]
    div = lambda n, d: int(n / d)          # C division truncates toward zero
    dx01, dy01, dx02, dy02, dx12, dy12 = x1 - x0, y1 - y0, x2 - x0, y2 - y0, x2 - x1, y2 - y1
    sa = sb = 0
    last = y1 if y1 == y2 else y1 - 1
    y = y0
    while y <= last:
        a, b = x0 + div(sa, dy01), x0 + div(sb, dy02)
        sa += dx01; sb += dx02
        out.append((y, min(a, b), max(a, b))); y += 1
    sa, sb = dx12 * (y - y1), dx02 * (y - y0)
    while y <= y2:
        a, b = x1 + div(sa, dy12), x0 + div(sb, dy02)
        sa += dx12; sb += dx02
        out.append((y, min(a, b), max(a, b))); y += 1
    return out


def spans(ro, ri, i, cx=90, cy=88):
    a0 = f32(f32(f32(135 + f32(i * 9.0)) + f32(0.8)) * D2R)
    a1 = f32(f32(f32(135 + f32((i + 1) * 9.0)) - f32(0.8)) * D2R)
    p0, p1 = corner(cx, cy, ro, a0), corner(cx, cy, ro, a1)
    p2, p3 = corner(cx, cy, ri, a1), corner(cx, cy, ri, a0)
    rows = {}
    for y, a, b in triangle(*p0, *p1, *p2) + triangle(*p0, *p2, *p3):
        rows.setdefault(y, set()).update(range(a, b + 1))
    out = []
    for y in sorted(rows):                  # merge each row into runs (one per row for these convex quads)
        xs = sorted(rows[y]); start = prev = xs[0]
        for x in xs[1:] + [None]:
            if x is not None and x == prev + 1: prev = x; continue
            out.append((y, start, prev))
            if x is not None: start = prev = x
    return out


def main():
    # the offsets must not depend on the gauge centre (x = 90, 240, 390)
    for ro, ri in RINGS:
        for i in range(SEGS):
            assert spans(ro, ri, i, 90) == spans(ro, ri, i, 240) == spans(ro, ri, i, 390)
    data, idx = [], []
    for ro, ri in RINGS:
        row = []
        for i in range(SEGS):
            row.append(len(data))
            for y, a, b in spans(ro, ri, i):
                data += [y, a, b - a + 1]
        row.append(len(data))
        idx.append(row)
    print('// generated by tools/gauge_segments.py: segment spans (dy, dx, width) relative to the gauge centre')
    print('static const int8_t SEG_SPANS[%d] PROGMEM = {' % len(data))
    for k in range(0, len(data), 24):
        print('  ' + ','.join(str(v) for v in data[k:k + 24]) + ',')
    print('};')
    print('static const uint16_t SEG_IDX[%d][%d] PROGMEM = {' % (len(RINGS), SEGS + 1))
    for (ro, ri), row in zip(RINGS, idx):
        print('  {%s},   // r %d..%d' % (','.join(str(v) for v in row), ro, ri))
    print('};')


if __name__ == '__main__':
    main()
